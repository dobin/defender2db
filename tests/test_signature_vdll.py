class VdllSigTests(unittest.TestCase):
    def snapshot(self, sig):
        details = sig.to_details()
        self.assertEqual(json.loads(json.dumps(details, allow_nan=False)), details)
        self.assertEqual(sig.decode_status, "decoded")
        return details

    def test_x86_image(self):
        sig = VdllSig(tlv(0x79, VDLL_X86_UNKNOWNSYS))
        self.assertEqual(sig.sig_type, "SIGNATURE_TYPE_VDLL_X86")
        self.assertEqual(sig.architecture, "x86")
        self.assertEqual(sig.machine, 0x14C)
        self.assertEqual(sig.machine_label, "x86 (i386)")
        self.assertEqual(sig.pe_format, "PE32")
        self.assertTrue(sig.is_dll)
        self.assertEqual(sig.module_name, "UNKNOWNSYS.DLL")
        self.assertEqual(sig.exports, ["UnimplementedAPI"])
        self.assertEqual(sig.export_count, 1)
        self.assertEqual(sig.imported_modules, [])
        self.assertEqual(sig.import_count, 0)
        self.assertEqual(sig.forwarders, {})
        self.assertEqual(sig.section_count, 1)
        self.assertEqual(sig.sections[0]["name"], ".text")
        self.assertEqual(sig.timestamp_iso, "2026-11-12T21:48:11Z")
        self.assertEqual(sig.overlay_size, 0)
        d = self.snapshot(sig)
        self.assertEqual(
            d["payload_sha256"],
            "663bd6cb4f4e5e0181fada0fbb9b8e4b1b683139a3181239f1844ec14a576122",
        )
        self.assertEqual(d["summary"], "PE32 x86 DLL 'UNKNOWNSYS.DLL', 1024 bytes, 1 exports, 0 imports")

    def test_x64_image(self):
        sig = VdllSig(tlv(0x7C, VDLL_X64_MSHTML))
        self.assertEqual(sig.sig_type, "SIGNATURE_TYPE_VDLL_X64")
        self.assertEqual(sig.architecture, "x64")
        self.assertEqual(sig.machine, 0x8664)
        self.assertEqual(sig.machine_label, "x64 (AMD64)")
        self.assertEqual(sig.pe_format, "PE32+")
        self.assertTrue(sig.is_dll)
        self.assertEqual(sig.module_name, "MSHTML.DLL")
        self.assertEqual(sig.export_count, 8)
        self.assertEqual(sig.exports, [
            "CreateHTMLPropertyPage", "DllCanUnloadNow", "DllGetClassObject",
            "PrintHTML", "RunHTMLApplication", "ShowHTMLDialog",
            "ShowHTMLDialogEx", "ShowModelessHTMLDialog",
        ])
        self.assertEqual(sig.import_count, 0)
        self.assertEqual(sig.timestamp_iso, "2026-11-12T21:58:52Z")
        d = self.snapshot(sig)
        self.assertEqual(
            d["payload_sha256"],
            "e8cdf82206e9ea28f48cf6908569aba198e41197c3d02d91a657c35fd007d4ea",
        )

    def test_machine_mismatch_is_partial(self):
        sig = VdllSig(tlv(0x79, VDLL_X64_MSHTML))
        self.assertEqual(sig.decode_status, "partial")
        self.assertTrue(any("does not match" in warning for warning in sig.decode_warnings))

    def test_non_pe_payload_is_partial(self):
        sig = VdllSig(tlv(0x7C, b"this is not a PE image"))
        self.assertEqual(sig.decode_status, "partial")
        self.assertFalse(sig.is_valid_pe)
        self.assertIn("MZ", sig.decode_warnings[0])

    def test_truncated_header_raises(self):
        with self.assertRaises(ValueError):
            VdllSig(b"\x79\x00")

    def test_dispatch(self):
        self.assertIsInstance(Vdm.decode_record(tlv(0x79, VDLL_X86_UNKNOWNSYS)), VdllSig)
        self.assertIsInstance(Vdm.decode_record(tlv(0x7C, VDLL_X64_MSHTML)), VdllSig)


if __name__ == "__main__":
    unittest.main()
